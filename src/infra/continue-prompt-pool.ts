// ===== 池读取（与 js-result-phrases 同模式：由外层注入通用设置读取函数）=====
let sharedReader: ((key: string) => string | undefined) | null = null;

/** 注入"通用设置"读取函数（bridge/entry 启动时调用） */
export function setContinueSettingReader(fn: (key: string) => string | undefined): void {
  sharedReader = fn;
}

/**
 * 随机取一条「让 AI 继续」文案。
 * 池来源：用户池（通用设置）→ 内置默认。
 * 未注入 reader / 池为空 / 读取抛错 一律回退内置默认，绝不返回空串。
 */
export function pickContinuePrompt(): string {
  let raw = '';
  try { raw = (sharedReader ? sharedReader(CONTINUE_PROMPT_KEY) : '') || ''; } catch (_) { raw = ''; }
  const list = raw.split('\n').map((s) => s.trim()).filter(Boolean);
  const pool = list.length > 0 ? list : DEFAULT_CONTINUE_PROMPTS;
  const picked = pool[Math.floor(Math.random() * pool.length)];
  return picked || DEFAULT_CONTINUE_PROMPTS[0];
}
